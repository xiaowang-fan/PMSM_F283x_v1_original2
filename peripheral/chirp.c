/*
 * chirp.c
 *
 * 工业级在线SFRA扫频器
 *
 * 特性：
 * 1. 对数分段扫频
 * 2. 固定周期数积分（工业标准）
 * 3. 在线同步检波
 * 4. 自动计算：
 *      - 幅值(dB)
 *      - 相位(deg)
 * 5. 自动跳过前N个周期暂态
 * 6. 自动切换频率
 * 7. 自动输出FRF结果
 *
 * 推荐：
 * cycle_num = 20
 * transient_cycles = 5
 *
 */

#include "chirp.h"
#include <math.h>

#define CHIRP_PI 3.14159265358979f

/* =========================================================
 * 全局对象
 * ========================================================= */

LogStepSweep_t g_speed_sweep;
LogStepSweep_t g_current_sweep;

/* =========================================================
 * 初始化扫频器
 * ========================================================= */
void Init_Log_Step_Sweep(
        LogStepSweep_t *v,
        float f0,
        float f1,
        float A,
        int   N_total,
        float cycle_num,
        float transient_cycles,
        float isr_freq)
{
    /* =====================================================
     * 用户参数
     * ===================================================== */

    v->f0 = f0;
    v->f1 = f1;

    v->A = A;

    v->N_total = N_total;

    v->cycle_num = cycle_num;

    v->transient_cycles = transient_cycles;

    v->ts = 1.0f / isr_freq;

    /* =====================================================
     * 初始频率
     * ===================================================== */

    v->freq_current = f0;

    /* =====================================================
     * 当前频点停留时间
     *
     * dwell = 周期数 / 频率
     * ===================================================== */

    v->dwell_time = v->cycle_num / v->freq_current;

    /* =====================================================
     * 暂态跳过时间
     * ===================================================== */

    v->transient_time = v->transient_cycles / v->freq_current;

    /* =====================================================
     * 状态变量
     * ===================================================== */

    v->phase = 0.0f;

    v->time_count = 0.0f;

    v->step_time_count = 0.0f;

    v->current_step = 0;

    v->is_running = 1;

    /* =====================================================
     * 在线DFT积分器
     * ===================================================== */

    v->ref_cos_sum = 0.0f;
    v->ref_sin_sum = 0.0f;

    v->fbk_cos_sum = 0.0f;
    v->fbk_sin_sum = 0.0f;

    v->sample_cnt = 0;

    /* =====================================================
     * 输出结果
     * ===================================================== */

    v->result_mag_dB = 0.0f;

    v->result_phase_deg = 0.0f;

    v->result_freq = 0.0f;

    v->result_ready_flag = 0;
}

/* =========================================================
 * 核心扫频函数
 *
 * 输入：
 *      fbk_val = 当前反馈值
 *
 * 输出：
 *      当前扰动
 * ========================================================= */
float Calc_Step_Log_Sweep(
        LogStepSweep_t *v,
        float fbk_val)
{
    float out_disturbance = 0.0f;

    /* =====================================================
     * 扫频运行中
     * ===================================================== */

    if (v->is_running)
    {
        /* =================================================
         * 当前相位
         * ================================================= */

        float phase_now = v->phase;

        /* =================================================
         * 输出扰动
         * ================================================= */

        out_disturbance =
                v->A * sinf(phase_now);

        /* =================================================
         * 同步检波基准
         * ================================================= */

        float sin_base = sinf(phase_now);

        float cos_base = cosf(phase_now);

        /* =================================================
         * 时间累计
         * ================================================= */

        v->time_count += v->ts;

        v->step_time_count += v->ts;

        /* =================================================
         * 跳过前 transient_cycles 周期
         * ================================================= */

        if (v->step_time_count >= v->transient_time)
        {
            /* =============================================
             * 在线同步DFT
             *
             * X = sum(x*cos) - j*sum(x*sin)
             * ============================================= */

            v->ref_cos_sum +=
                    out_disturbance * cos_base;

            v->ref_sin_sum +=
                    out_disturbance * sin_base;

            v->fbk_cos_sum +=
                    fbk_val * cos_base;

            v->fbk_sin_sum +=
                    fbk_val * sin_base;

            v->sample_cnt++;
        }

        /* =================================================
         * 相位更新
         * ================================================= */

        v->phase +=
                2.0f
                * CHIRP_PI
                * v->freq_current
                * v->ts;

        if (v->phase >= 2.0f * CHIRP_PI)
        {
            v->phase -= 2.0f * CHIRP_PI;
        }

        /* =================================================
         * 当前频点结束
         * ================================================= */

        if (v->step_time_count >= v->dwell_time)
        {
            /* =============================================
             * 防止积分点过少
             * ============================================= */

            if (v->sample_cnt > 20)
            {
                /* =========================================
                 * 输入复数谱
                 * ========================================= */

                float X_real =
                        v->ref_cos_sum
                        / (float)v->sample_cnt;

                float X_imag =
                       -v->ref_sin_sum
                        / (float)v->sample_cnt;

                /* =========================================
                 * 输出复数谱
                 * ========================================= */

                float Y_real =
                        v->fbk_cos_sum
                        / (float)v->sample_cnt;

                float Y_imag =
                       -v->fbk_sin_sum
                        / (float)v->sample_cnt;

                /* =========================================
                 * 幅值
                 * ========================================= */

                float X_mag =
                        sqrtf(
                            X_real * X_real
                          + X_imag * X_imag);

                float Y_mag =
                        sqrtf(
                            Y_real * Y_real
                          + Y_imag * Y_imag);

                /* =========================================
                 * 相位
                 * ========================================= */

                float X_phase =
                        atan2f(X_imag, X_real);

                float Y_phase =
                        atan2f(Y_imag, Y_real);

                /* =========================================
                 * 防止除0
                 * ========================================= */

                if (X_mag > 1e-6f)
                {
                    /* =====================================
                     * 幅值(dB)
                     * ===================================== */

                    v->result_mag_dB =
                            20.0f
                            * log10f(Y_mag / X_mag);

                    /* =====================================
                     * 相位差
                     * ===================================== */

                    float phase_diff =
                            Y_phase - X_phase;

                    /* =====================================
                     * 限制到 [-PI, PI]
                     * ===================================== */

                    while (phase_diff > CHIRP_PI)
                    {
                        phase_diff -=
                                2.0f * CHIRP_PI;
                    }

                    while (phase_diff < -CHIRP_PI)
                    {
                        phase_diff +=
                                2.0f * CHIRP_PI;
                    }

                    /* =====================================
                     * 转换为角度
                     * ===================================== */

                    v->result_phase_deg =
                            phase_diff
                            * 180.0f
                            / CHIRP_PI;

                    /* =====================================
                     * 当前频率
                     * ===================================== */

                    v->result_freq =
                            v->freq_current;

                    /* =====================================
                     * 通知上位机
                     * ===================================== */

                    v->result_ready_flag = 1;
                }
            }

            /* =================================================
             * 清空积分器
             * ================================================= */

            v->ref_cos_sum = 0.0f;
            v->ref_sin_sum = 0.0f;

            v->fbk_cos_sum = 0.0f;
            v->fbk_sin_sum = 0.0f;

            v->sample_cnt = 0;

            /* =================================================
             * 时间复位
             * ================================================= */

            v->step_time_count = 0.0f;

            /* =================================================
             * 下一频点
             * ================================================= */

            v->current_step++;

            if (v->current_step < v->N_total)
            {
                float power_exp =
                        (float)v->current_step
                        / (float)(v->N_total - 1);

                /* =========================================
                 * 下一频率
                 * ========================================= */

                v->freq_current =
                        v->f0
                        * powf(
                            v->f1 / v->f0,
                            power_exp);

                /* =========================================
                 * 自动更新停留时间
                 * ========================================= */

                v->dwell_time =
                        v->cycle_num
                        / v->freq_current;

                /* =========================================
                 * 自动更新暂态时间
                 * ========================================= */

                v->transient_time =
                        v->transient_cycles
                        / v->freq_current;
            }
            else
            {
                /* =========================================
                 * 扫频结束
                 * ========================================= */

                v->is_running = 0;

                v->result_freq = -1.0f;
            }
        }
    }
    else
    {
        out_disturbance = 0.0f;
    }

    return out_disturbance;
}
